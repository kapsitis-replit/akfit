import { defineConfig } from 'astro/config';
import react from '@astrojs/react';
import icon from 'astro-icon';
import tailwindcss from '@tailwindcss/vite';
import { readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

/**
 * Writes dist/_redirects for Cloudflare static assets. wrangler.jsonc uses
 * html_handling "none" (so /page.html is served as-is, never redirected), which
 * means Cloudflare does no URL guessing at all. The old Zeabur/Caddy host served
 * every page both as /page.html and /page, and links, bookmarks and n8n emails
 * may use either. So for every top-level page we add a 200 *rewrite*: /page
 * serves page.html without redirecting, and the query string is kept.
 */
function extensionlessRewrites() {
  return {
    name: 'akfit:extensionless-rewrites',
    hooks: {
      'astro:build:done': async ({ dir }) => {
        const out = fileURLToPath(dir);
        const pages = (await readdir(out))
          .filter((f) => f.endsWith('.html') && f !== '404.html')
          .map((f) => f.slice(0, -'.html'.length));
        const lines = [
          '# Generated by astro.config.mjs (extensionlessRewrites). Do not edit.',
          // The landing page moved from /indexreal.html to / on 2026-11-16.
          '/indexreal.html / 301',
          '/indexreal / 301',
          '/ /index.html 200',
          ...pages.filter((p) => p !== 'index').map((p) => `/${p} /${p}.html 200`),
          '/index /index.html 200',
        ];
        await writeFile(new URL('_redirects', dir), lines.join('\n') + '\n');
      },
    },
  };
}

export default defineConfig({
  site: 'https://www.akfitness.lv',
  output: 'static',
  build: {
    // Emit `online-coaching.html` (not `online-coaching/index.html`) so every
    // existing URL, bookmark and search result keeps working.
    format: 'file',
  },
  // Keep `/indexreal.html` etc. exactly as they are today.
  trailingSlash: 'ignore',
  // OFF on purpose: Astro's HTML compression drops line breaks between text and
  // inline tags (e.g. "ir\n<strong>distances" → "ir<strong>distances"), which
  // glues words together in the legal pages and headings. Gzip on the server
  // makes the size difference negligible.
  compressHTML: false,
  integrations: [
    // React is used ONLY for islands in src/islands (Magic UI effects),
    // each hydrated with client:visible. Everything else ships zero JS.
    react(),
    // Icons are inlined as SVG at build time (replaces the Iconify runtime).
    icon({ include: { solar: ['*'], mdi: ['*'] } }),
    extensionlessRewrites(),
  ],
  image: {
    // Remote images we optimise at build time (AVIF/WebP + srcset).
    domains: ['images.unsplash.com', 'hoirqrkdgbmvpwutwuwj.supabase.co'],
  },
  vite: {
    plugins: [tailwindcss()],
  },
});
